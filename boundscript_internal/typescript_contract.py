"""Deterministic TypeScript signature consumer; no candidate or model access."""
import json
import re


def generate_contract_check(contract_module, function_type, implementation_module, function_name):
    """Return a no-runtime-oracle assignability check for named TypeScript exports.

    Module specifiers are resolved by TypeScript relative to the generated file.
    Callers own staging and compiler/sandbox policy; this helper only renders text.
    """
    for name in (function_type, function_name):
        if not isinstance(name, str) or not re.fullmatch(r'[A-Za-z_$][A-Za-z0-9_$]*', name):
            raise ValueError('Expected a simple TypeScript export name')
    for module in (contract_module, implementation_module):
        if not isinstance(module, str) or not module or any(ord(c) < 32 for c in module):
            raise ValueError('Expected a nonempty module specifier without control characters')
    return (
        '// Generated by BoundScript infrastructure; not by the implementation agent.\n'
        f'import type {{ {function_type} as Contract }} from {json.dumps(contract_module)};\n'
        f'import {{ {function_name} as implementation }} from {json.dumps(implementation_module)};\n'
        '\n'
        'const checked: Contract = implementation;\n'
        'void checked;\n'
    )
